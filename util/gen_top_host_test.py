"""Check gen_top_host.py against the Rust code that topgen generates for each top.

Host tools use the constants and enums in hw/top_<top>/sw/autogen/chip/ today. The host
description must give the same addresses and enum variants, so that host tools can move
from those compile-time definitions to the run-time description.
"""
import re
import sys

import hjson
import pytest

from gen_top_host import (REPO_TOP, host_description, jtag_idcodes, load_otp_mmap,
                          parse_localparams)
from topgen.lib import load_completecfg_and_blocks

TOPS = ["egret", "dragonfly", "scafi_deprecated"]

# The Rust enum generated by topgen for each enumeration in the host description.
RUST_ENUMS = {
    ("alert_handler", "peripherals"): "AlertPeripheral",
    ("alert_handler", "alerts"): "AlertId",
    ("pinmux", "peripheral_in"): "PinmuxPeripheralIn",
    ("pinmux", "insel"): "PinmuxInsel",
    ("pinmux", "mio_out"): "PinmuxMioOut",
    ("pinmux", "outsel"): "PinmuxOutsel",
    ("pinmux", "direct_pads"): "DirectPads",
    ("pinmux", "muxed_pads"): "MuxedPads",
    ("pwrmgr", "wakeups"): "PowerManagerWakeUps",
    ("pwrmgr", "reset_requests"): "PowerManagerResetRequests",
    ("rstmgr", "sw_resets"): "ResetManagerSwResets",
    ("clkmgr", "gateable_clocks"): "GateableClocks",
    ("clkmgr", "hintable_clocks"): "HintableClocks",
}

CONST_RE = re.compile(r"^pub const (\w+): usize = (0x[0-9A-Fa-f]+|\d+);$", re.MULTILINE)
ENUM_RE = re.compile(r"^pub enum (\w+) \{\n(.*?)^\}", re.MULTILINE | re.DOTALL)
VARIANT_RE = re.compile(r"^    (\w+) = (\d+),$", re.MULTILINE)
ALERT_MAPPING_RE = re.compile(r"^    // (\w+) -> AlertPeripheral::(\w+)$", re.MULTILINE)


def rust_source(top: str, addr_space: str) -> str:
    suffix = "" if addr_space == "hart" else "_" + addr_space
    return (REPO_TOP / f"hw/top_{top}/sw/autogen/chip/top_{top}{suffix}.rs").read_text()


def rust_consts(source: str):
    return {name: int(value, 0) for name, value in CONST_RE.findall(source)}


def rust_enums(source: str):
    return {
        name: {variant: int(value) for variant, value in VARIANT_RE.findall(body)}
        for name, body in ENUM_RE.findall(source)
    }


@pytest.fixture(scope="module", params=TOPS)
def top(request):
    completecfg_path = (REPO_TOP / f"hw/top_{request.param}/data/autogen/"
                        f"top_{request.param}.gen.hjson")
    completecfg, name_to_block = load_completecfg_and_blocks(completecfg_path, REPO_TOP)
    jtag_id_pkg = REPO_TOP / f"hw/top_{request.param}/rtl/jtag_id_pkg.sv"
    return request.param, host_description(
        completecfg, name_to_block, jtag_id_pkg.read_text() if jtag_id_pkg.exists() else None,
        load_otp_mmap(completecfg, REPO_TOP))


def test_name(top):
    name, desc = top
    assert desc["name"] == name


def test_addresses(top):
    name, desc = top
    for addr_space, regions in desc["addr_spaces"].items():
        expected = {}
        for key in ("devices", "memories"):
            for region_name, region in regions[key].items():
                expected[f"{region_name.upper()}_BASE_ADDR"] = region["base_addr"]
                expected[f"{region_name.upper()}_SIZE_BYTES"] = region["size_bytes"]
        prefix = f"TOP_{name.upper()}_"
        if addr_space != "hart":
            prefix += f"{addr_space.upper()}_"
        for subrange_name, region in regions["subranges"].items():
            expected[f"{prefix}{subrange_name.upper()}_BASE_ADDR"] = region["base_addr"]
            expected[f"{prefix}{subrange_name.upper()}_SIZE_BYTES"] = region["size_bytes"]

        consts = rust_consts(rust_source(name, addr_space))
        for const_name, value in expected.items():
            assert consts.get(const_name) == value, const_name
        # Every address constant in the Rust code must be in the description. The
        # template adds SOC_PROXY_RAM_CTN_* as an alias of SOC_PROXY_CTN_*.
        for const_name in consts:
            if const_name.endswith(("_BASE_ADDR", "_SIZE_BYTES")) and \
                    not const_name.startswith("SOC_PROXY_RAM_CTN_"):
                assert const_name in expected, const_name


def test_enums(top):
    name, desc = top
    enums = rust_enums(rust_source(name, "hart"))
    for (section, key), rust_name in RUST_ENUMS.items():
        if section in desc:
            assert desc[section][key] == enums[rust_name], rust_name
        else:
            assert rust_name not in enums, rust_name


def test_alert_mapping(top):
    name, desc = top
    if "alert_handler" not in desc:
        pytest.skip("no alert handler")
    mapping = dict(ALERT_MAPPING_RE.findall(rust_source(name, "hart")))
    assert desc["alert_handler"]["alert_to_peripheral"] == mapping


def test_pad_counts(top):
    name, desc = top
    if "pinmux" not in desc:
        pytest.skip("no pinmux")
    consts = rust_consts(rust_source(name, "hart"))
    assert desc["pinmux"]["num_mio_pads"] == consts["NUM_MIO_PADS"]
    assert desc["pinmux"]["num_dio_pads"] == consts["NUM_DIO_PADS"]


# The OpenOCD target configuration of each TAP, whose default _CPUTAPID is the IDCODE.
OPENOCD_CFGS = {
    "dm_idcode": "util/openocd/target/lowrisc-{}.cfg",
    "lc_idcode": "util/openocd/target/lowrisc-{}-lc.cfg",
}
CPUTAPID_RE = re.compile(r"^\s*set _CPUTAPID (0x[0-9A-Fa-f]+)$", re.MULTILINE)


def test_jtag_idcodes(top):
    name, desc = top
    cfgs = {key: REPO_TOP / path.format(name) for key, path in OPENOCD_CFGS.items()}
    if not all(cfg.exists() for cfg in cfgs.values()):
        assert "dm_idcode" not in desc and "lc_idcode" not in desc
        pytest.skip("no OpenOCD configuration")
    for key, cfg in cfgs.items():
        assert desc[key] == int(CPUTAPID_RE.search(cfg.read_text()).group(1), 0), key


def test_localparam_literals():
    params = parse_localparams("""
        localparam logic [3:0] A = 4'hA;  // comment
        localparam logic [6:0] B = 7'b110_1111;
        localparam logic [5:0] C = 6'o17;
        localparam logic [3:0] D = 4'd12;
        localparam logic [21:0] E = {
            A,     // A
            B,
            1'b1, {C, D}
        };
    """)
    assert params == {
        "A": (0xa, 4),
        "B": (0x6f, 7),
        "C": (0o17, 6),
        "D": (12, 4),
        "E": ((((((0xa << 7) | 0x6f) << 1) | 1) << 10) | (0o17 << 4) | 12, 22),
    }


@pytest.mark.parametrize("text", [
    "localparam logic [3:0] A = 5'h1;",  # width mismatch
    "localparam logic [3:0] A = 4'h1f;",  # value too wide
    "localparam logic [3:0] A = B;",  # unknown name
    "localparam logic [3:0] A = 4;",  # unsized literal
])
def test_localparam_errors(text):
    with pytest.raises(ValueError):
        parse_localparams(text)


def idcode(tap_type: int) -> str:
    return f"32'h1000{tap_type:x}cdf"


def test_jtag_idcode_selection():
    # The first IDCODE with each TAP type bit wins; other localparams are ignored.
    text = f"""
        localparam logic [31:0] OTHER = {idcode(1)};
        localparam logic [31:0] X_IDCODE = {idcode(4)};
        localparam logic [31:0] LC_IDCODE = {idcode(2)};
        localparam logic [31:0] DM_IDCODE = {idcode(1)};
        localparam logic [31:0] BOTH_IDCODE = {idcode(3)};
    """
    assert jtag_idcodes(text) == {"dm_idcode": 0x10001cdf, "lc_idcode": 0x10002cdf}
    # One combined TAP gives both.
    text = f"localparam logic [31:0] COMBINED_JTAG_IDCODE = {idcode(3)};"
    assert jtag_idcodes(text) == {"dm_idcode": 0x10003cdf, "lc_idcode": 0x10003cdf}
    assert jtag_idcodes("localparam logic [3:0] A = 4'h1;") == {}
    with pytest.raises(ValueError):
        jtag_idcodes("localparam logic [15:0] SHORT_IDCODE = 16'h1cdf;")


